.ALIGN 2

// LCD_1602_PULSE: w0 = nibble|flags; latch with EN high then low
LCD_1602_PULSE:
	STP X29, X30, [SP, -32]!
	STR X19, [SP, 16]
	MOV W19, W0
	ORR W0, W19, LCD_1602_EN
	_I2C_WRITE_BYTE X0
	_MICROSLEEP 1
	MOV W1, LCD_1602_EN
	BIC W0, W19, W1
	_I2C_WRITE_BYTE X0
	_MICROSLEEP 50
	LDR X19, [SP, 16]
	LDP X29, X30, [SP], 32
	RET

// LCD_1602_SEND: w0 = byte, w1 = mode (0 = command, RS = data)
LCD_1602_SEND:
	STP X29, X30, [SP, -32]!
	STP X19, X20, [SP, 16]
	MOV W19, W0
	MOV W20, W1
	AND W0, W19, 0XF0        // HIGH NIBBLE
	ORR W0, W0, W20
	ORR W0, W0, LCD_1602_BL
	BL LCD_1602_PULSE
	LSL W0, W19, 4           // LOW NIBBLE
	AND W0, W0, 0XF0
	ORR W0, W0, W20
	ORR W0, W0, LCD_1602_BL
	BL  LCD_1602_PULSE
	LDP X19, X20, [SP, 16]
	LDP X29, X30, [SP], 32
	RET

LCD_1602_CMD:
	MOV W1, 0
	B LCD_1602_SEND

LCD_1602_CHAR:
	MOV W1, LCD_1602_RS
	B LCD_1602_SEND

// LCD_1602_PRINT: x0 = pointer to null-terminated string
LCD_1602_PRINT:
	STP X29, X30, [SP, -32]!
	STR X19, [SP, 16]
	MOV X19, X0
1:
	LDRB W0, [X19], 1
	CBZ W0, 2f
	BL LCD_1602_CHAR
	B 1b
2:
	LDR X19, [SP, 16]
	LDP X29, X30, [SP], 32
	RET

// LCD_1602_INIT: HD44780 4-bit init sequence
LCD_1602_INIT:
	STP X29, X30, [SP, -16]!
	_MICROSLEEP 50000

	MOV W0, (0X30 | LCD_1602_BL)
	BL LCD_1602_PULSE
	_MICROSLEEP 4500
	MOV W0, (0X30 | LCD_1602_BL)
	BL LCD_1602_PULSE
	_MICROSLEEP 200
	MOV W0, (0X30 | LCD_1602_BL)
	BL LCD_1602_PULSE
	_MICROSLEEP 200

	MOV W0, (0X20 | LCD_1602_BL)       // SWITCH TO 4-BIT MODE
	BL LCD_1602_PULSE
	_MICROSLEEP 200

	MOV W0, 0X28              // 4-BIT, 2 LINES, 5X8 FONT
	BL LCD_1602_CMD
	MOV W0, 0X0C              // DISPLAY ON, CURSOR OFF
	BL LCD_1602_CMD
	MOV W0, 0X0             // CLEAR
	BL LCD_1602_CMD
	_MICROSLEEP 2000
	MOV W0, 0X06            // ENTRY MODE: INCREMENT
	BL LCD_1602_CMD
	LDP X29, X30, [SP], 16
	RET

.ENDIF
