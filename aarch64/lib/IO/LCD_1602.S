.IFNDEF LCD_1602
.EQU LCD_1602,1

//.INCLUDE "IO/LOG_TEXT.S"
.INCLUDE "SYS/SLEEP.S"
.INCLUDE "IO/I2C.S"

.EQU LCD_1602_ADDR, 0x27
.EQU LCD_1602_BL, 0x08
.EQU LCD_1602_EN, 0x04
.EQU LCD_1602_RS, 0x01

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////

.MACRO _LCD_1602_INIT
	SUB SP,SP,16
	STP LR,X0,[SP,0]
	BL LCD_1602_INIT
	LDP LR,X0,[SP,0]
	ADD SP,SP,16
.ENDM

.MACRO _LCD_1602_PRINT ADDRESS // LABEL OF NULL-TERMINATED STRING
	SUB SP,SP,16
	STP LR,X0,[SP,0]
	ADR X0, \ADDRESS
	BL LCD_1602_PRINT
	LDP LR,X0,[SP,0]
	ADD SP,SP,16
.ENDM

.MACRO _LCD_1602_SET_CURSOR ROW COLUMN
	SUB SP,SP,32
	STP LR,X0,[SP,0]
	STR X1,[SP,16]
	MOV X0, \ROW
	MOV X1, \COLUMN
	BL LCD_1602_SET_CURSOR
	LDP LR,X0,[SP,0]
	LDR X1,[SP,16]
	ADD SP,SP,32
.ENDM

.MACRO _LCD_1602_CLEAR
	SUB SP,SP,16
	STP LR,X0,[SP,0]
	MOV W0, 0X01
	BL LCD_1602_CMD
	LDP LR,X0,[SP,0]
	ADD SP,SP,16
.ENDM
	
.MACRO _LCD_1602_SHIFT_LEFT
	SUB SP,SP,16
	STP LR,X0,[SP,0]
	MOV W0, 0X18
	BL LCD_1602_CMD
	LDP LR,X0,[SP,0]
	ADD SP,SP,16
.ENDM

.MACRO _LCD_1602_SHIFT_RIGHT
	SUB SP,SP,16
	STP LR,X0,[SP,0]
	MOV W0, 0X1C
	BL LCD_1602_CMD
	LDP LR,X0,[SP,0]
	ADD SP,SP,16
.ENDM

.MACRO _LCD_1602_CURSOR_LEFT
	SUB SP,SP,16
	STP LR,X0,[SP,0]
	MOV W0, 0X10
	BL LCD_1602_CMD
	LDP LR,X0,[SP,0]
	ADD SP,SP,16
.ENDM

.MACRO _LCD_1602_CURSOR_RIGHT
	SUB SP,SP,16
	STP LR,X0,[SP,0]
	MOV W0, 0X14
	BL LCD_1602_CMD
	LDP LR,X0,[SP,0]
	ADD SP,SP,16
.ENDM

.MACRO _LCD_1602_CUSTOM_CHAR ENTRY ADDRESS// W0 = 0-7 for custom char entry, W1 = ADDR of 8-byte custom char definition
	SUB SP,SP,32
	STP LR,X0,[SP,0]
	STR X1,[SP,16]
	MOV X0, \ENTRY
	ADR X1, \ADDRESS
	BL LCD_1602_CUSTOM_CHAR
	LDP LR,X0,[SP,0]
	LDR X1,[SP,16]
	ADD SP,SP,32
.ENDM

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////

.ALIGN 2

// LCD_1602_PULSE: w0 = nibble|flags; latch with EN high then low
LCD_1602_PULSE:
	STP X19, LR, [SP, -16]!
	MOV W19, W0
	ORR W0, W19, LCD_1602_EN
	_I2C_WRITE_BYTE X0
	_MICROSLEEP 1
	MOV W1, LCD_1602_EN
	BIC W0, W19, W1
	_I2C_WRITE_BYTE X0
	_MICROSLEEP 50
	LDP X19, LR, [SP], 16
	RET

// LCD_1602_SEND: w0 = byte, w1 = mode (0 = command, RS = data)
LCD_1602_SEND:
	STP X29, LR, [SP, -32]!
	STP X19, X20, [SP, 16]
	MOV W19, W0
	MOV W20, W1
	AND W0, W19, 0XF0        // HIGH NIBBLE
	ORR W0, W0, W20
	ORR W0, W0, LCD_1602_BL
	BL LCD_1602_PULSE
	LSL W0, W19, 4           // LOW NIBBLE
	AND W0, W0, 0XF0
	ORR W0, W0, W20
	ORR W0, W0, LCD_1602_BL
	BL  LCD_1602_PULSE
	LDP X19, X20, [SP, 16]
	LDP X29, LR, [SP], 32
	RET

LCD_1602_CMD:
	MOV W1, 0
	B LCD_1602_SEND

LCD_1602_SET_CURSOR: // B0 ROW, B1 COLUMN
	AND X0, X0, 1
	LSL X0, X0, 6
	ADD X0, X0, X1
	ADD X0, X0, 0X80
	MOV W1, 0
	B LCD_1602_SEND

LCD_1602_CHAR:
	MOV W1, LCD_1602_RS
	B LCD_1602_SEND

LCD_1602_CUSTOM_CHAR: // w0 = slot (0-7), x1 = pointer to 8 row bytes
	STP  LR, X19, [SP, -32]!
	STP  X20, XZR, [SP, 16]
	MOV  X19, X1                // ROW POINTER (SURVIVES BL CALLS)
	LSL  W0, W0, 3
	ORR  W0, W0, 0X40           // CGRAM ADDRESS = 0X40 | SLOT*8
	BL   LCD_1602_CMD
	MOV  W20, 8                 // 8 ROWS
1:  LDRB W0, [X19], 1
	BL   LCD_1602_CHAR        // RS=1 DATA WRITE, ADDRESS AUTO-INCREMENTS
	SUBS W20, W20, 1
	B.NE 1b
	MOV  W0, 0X80               // SWITCH BACK TO DDRAM
	BL   LCD_1602_CMD
	LDP  X20, XZR, [SP, 16]
	LDP  LR, X19, [SP], 32
	RET

// LCD_1602_PRINT: x0 = pointer to null-terminated string
LCD_1602_PRINT:
	STP LR, X19, [SP, -16]!
	MOV X19, X0
1:
	LDRB W0, [X19], 1
	CBZ W0, 2f
	BL LCD_1602_CHAR
	B 1b
2:
	LDP LR, X19, [SP], 16
	RET

// LCD_1602_INIT: HD44780 4-bit init sequence
LCD_1602_INIT:
	STR LR, [SP, -16]!
	_MICROSLEEP 50000

	MOV W0, (0X30 | LCD_1602_BL)
	BL LCD_1602_PULSE
	_MICROSLEEP 4500
	MOV W0, (0X30 | LCD_1602_BL)
	BL LCD_1602_PULSE
	_MICROSLEEP 200
	MOV W0, (0X30 | LCD_1602_BL)
	BL LCD_1602_PULSE
	_MICROSLEEP 200

	MOV W0, (0X20 | LCD_1602_BL)       // SWITCH TO 4-BIT MODE
	BL LCD_1602_PULSE
	_MICROSLEEP 200

	MOV W0, 0X28              // 4-BIT, 2 LINES, 5X8 FONT
	BL LCD_1602_CMD
	MOV W0, 0X0C              // DISPLAY ON, CURSOR OFF
	BL LCD_1602_CMD
	MOV W0, 0X01             // CLEAR
	BL LCD_1602_CMD
	_MICROSLEEP 2000
	MOV W0, 0X06            // ENTRY MODE: INCREMENT
	BL LCD_1602_CMD
	
	LDR LR, [SP], 16
	RET

.ENDIF
